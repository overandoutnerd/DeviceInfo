@Composable
fun DeviceInfoAppTheme(
    darkTheme: Boolean,
    // Dynamic color is available on Android 12+, but this app uses a
    // deliberate, branded (Samsung Health inspired) palette by default
    // so the design stays consistent across every device.
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

//    val colorScheme = if (darkTheme) darkScheme else lightScheme
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = Color.Transparent.toArgb()
            window.navigationBarColor = Color.Transparent.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }
    CompositionLocalProvider(
        LocalIsDarkTheme provides darkTheme,
        // Scaffold uses a transparent containerColor throughout this app (so
        // the gradient background shows through), and Material3 can't derive
        // a sensible on-color for a transparent container - it falls back to
        // whatever LocalContentColor already is, and Compose's own built-in
        // default for that is a hardcoded Color.Black, completely ignoring
        // the theme. Every Text/Icon that doesn't explicitly set its own
        // color has been silently relying on that broken default, which is
        // why so much text/iconography stayed black in dark mode. Providing
        // a real, theme-correct default here fixes all of them at once.
        LocalContentColor provides colorScheme.onBackground
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = DeviceInfoAppTypography,
            content = content
        )
    }
}